#pragma once

#include <chargefw/charges/charge_set.h>
#include <chargefw/io/molecule_record.h>
#include <chargefw/version.h>

#include <algorithm>
#include <cstddef>
#include <ostream>
#include <print>
#include <string>

namespace chargefw::io::detail {

[[nodiscard]] inline auto safe_line(std::string value) -> std::string {
    std::ranges::replace_if(
        value, [](const char character) { return character == '\r' || character == '\n'; }, '_');
    return value;
}

inline auto write_generator_comment(std::ostream& output, const charges::ChargeSet& charge_set)
    -> void {
    std::print(output, "Generated by ChargeFW {}", CHARGEFW_VERSION_STRING);
    std::print(output, "; method={}", safe_line(std::string{charge_set.method_id()}));
    if (const auto parameter_set_id = charge_set.parameter_set_id(); parameter_set_id.has_value()) {
        std::print(output, "; parameter_set={}", safe_line(std::string{*parameter_set_id}));
    }
    std::println(output);
}

[[nodiscard]] inline auto record_display_name(const ImportedMoleculeRecord& record,
                                              const std::size_t index) -> std::string {
    auto result = record.identity.record_id.empty() ? std::string{record.molecule.name()}
                                                    : record.identity.record_id.display_string();
    if (result.empty()) {
        result = "molecule_" + std::to_string(index + 1);
    }
    return result;
}

} // namespace chargefw::io::detail
