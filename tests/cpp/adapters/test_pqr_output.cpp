[[nodiscard]] auto read_pdb(const std::string_view text) -> adapters::ImportedMoleculeRecord {
    auto input = std::istringstream{std::string{text}};
    auto reader = pdb::PdbReader{input, "input.pdb"};
    auto record = reader.next();
    REQUIRE(record.has_value());
    return std::move(*record);
}

// One oxygen atom whose author residue number, chain ID, and atom name are given.
[[nodiscard]] auto read_mmcif_oxygen(const std::string_view sequence, const std::string_view chain,
                                     const std::string_view atom)
    -> adapters::ImportedMoleculeRecord {
    auto input = std::istringstream{std::format(
        "data_oxygen\nloop_\n_atom_site.group_PDB\n_atom_site.id\n_atom_site.type_symbol\n"
        "_atom_site.label_atom_id\n_atom_site.label_alt_id\n_atom_site.label_comp_id\n"
        "_atom_site.label_asym_id\n_atom_site.label_seq_id\n_atom_site.pdbx_PDB_ins_code\n"
        "_atom_site.Cartn_x\n_atom_site.Cartn_y\n_atom_site.Cartn_z\n_atom_site.occupancy\n"
        "_atom_site.B_iso_or_equiv\n_atom_site.pdbx_formal_charge\n_atom_site.auth_seq_id\n"
        "_atom_site.auth_comp_id\n_atom_site.auth_asym_id\n_atom_site.auth_atom_id\n"
        "_atom_site.pdbx_PDB_model_num\n"
        "HETATM 1 O O . HOH A 1 ? 0.000 0.000 0.000 1.00 20.00 0 {} HOH {} {} 1\n",
        sequence, chain, atom)};
    auto reader = mmcif::MmcifReader{input, "input.cif"};
    auto record = reader.next();
    REQUIRE(record.has_value());
    return std::move(*record);
}

[[nodiscard]] auto formal(const std::size_t atom_count) -> charges::ChargeSet {
    return charges::ChargeSet{
        "formal",
        {{.target = {.molecule_index = 0},
          .charges = charges::AtomicCharges{std::vector<double>(atom_count, 0.0)}}}};
}

